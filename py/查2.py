# 查：话已经传了一圈，回到你耳朵里是歪的。你一天去问一户"你听到的是什么、从谁那听的"。
# 可它跟你讲的时候，也照自己的脾气再改一回。脾气每局重新分给六户，名字不告诉你谁是什么脾气。
# 三天问完，指出"是谁先把话说歪的"（第一个改了句子、而且改得最远的那一户），以及它改了哪一格。
# 查2（19:49）：只问两天；听岔的地方走一个圈（不再两下岔回原处）；揭开写对错、画出到村口那条链。
# 用法：python3 查2.py 种子 [问的人 问的人 指认的人]   不给后面就只打印开局。
import random, sys
from 村 import 夸, 怕, 好心, 耳背, 省字, 原样, 东西, 念
import 村 as _村
_村.东西邻.clear(); _村.东西邻.update({"井": "鸡窝", "鸡窝": "坟", "坟": "庙", "庙": "寡妇家", "寡妇家": "柿子树", "柿子树": "井"})

脾气们 = [夸, 怕, 好心, 耳背, 省字, 原样]
名 = ["王婆", "李瞎子", "赵屠", "孙先生", "钱寡妇", "小六"]
邻 = {"王婆": ["李瞎子", "赵屠"], "李瞎子": ["王婆", "孙先生", "小六"], "赵屠": ["王婆", "钱寡妇"],
      "孙先生": ["李瞎子", "钱寡妇"], "钱寡妇": ["赵屠", "孙先生", "小六"], "小六": ["李瞎子", "钱寡妇"]}

def 开局(seed):
    r = random.Random(seed)
    p = 脾气们[:]; r.shuffle(p)
    村 = dict(zip(名, p))
    起 = r.choice(名); 在 = r.choice(["柿子树", "井"])
    s = {"在": 在, "物": 东西[在], "动": 0, "久": 0}
    听过 = {}; 队 = [(起, s, "你")]
    while 队:
        人, 句, 从 = 队.pop(0)
        if 人 in 听过: continue
        句 = dict(句); 改 = 村[人](句)
        听过[人] = (句, 从, 改)
        n = 邻[人][:]; r.shuffle(n)
        for x in n[:2]: 队.append((x, 句, 人))
    return 村, 起, s, 听过

def 讲给你(村, 人, 句):
    s = dict(句); 村[人](s); return s

if __name__ == "__main__":
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    村, 起, s, 听过 = 开局(seed)
    print(f"你那天对{起}说：{念(s)}")
    末 = max(听过.items(), key=lambda kv: kv[1][0]["动"] * 2 + kv[1][0]["久"] + (kv[1][0]["在"] != s["在"]) * 2)
    print(f"今天村口有人当面问你：听说{念(末[1][0])[1:]}？")
    问 = sys.argv[2:4]
    for d, 谁 in enumerate(问):
        if 谁 not in 听过: print(f"第{d+1}天 {谁}：没听说。"); continue
        句, 从, _ = 听过[谁]
        print(f"第{d+1}天 {谁}：我听{从}说，{念(讲给你(村, 谁, 句))[1:]}")
    if len(sys.argv) > 4:
        指 = sys.argv[4]
        print("—— 揭开 ——")
        for 人 in 名:
            if 人 in 听过:
                句, 从, 改 = 听过[人]; print(f"  {人:4} 从{从:4} {改:8} → {念(句)}")
        路 = []; 人 = 末[0]
        while 人 != "你": 路.append(人); 人 = 听过[人][1]
        路 = 路[::-1]; 前 = s; 凶 = None
        for 人 in 路:
            if 听过[人][0] != 前 and 凶 is None: 凶 = 人
            前 = 听过[人][0]
        print("到村口那条：你 → " + " → ".join(路))
        print(f"头一个真改了的：{凶}　你指的是 {指}　" + ("对了" if 指 == 凶 else "不对"))
