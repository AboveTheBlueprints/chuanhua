# 一句话传出去：每家照自己的脾气改一样，传给邻居。看它回到你耳朵里是什么样。
import random, sys

# 一句话 = 四格：谁、在哪、做了什么、做的是什么
动作梯 = ["看了看", "摸了摸", "拿了", "偷了", "砸了"]           # 越往右越坏
程度梯 = ["一眼", "一会儿", "半天", "一整夜"]
东西邻 = {"井": "鸡窝", "鸡窝": "坟", "坟": "庙", "庙": "井",
          "柿子树": "寡妇家", "寡妇家": "柿子树"}
东西 = {"井": "井绳", "鸡窝": "鸡蛋", "坟": "供果", "庙": "香炉", "柿子树": "柿子", "寡妇家": "针线"}

# 脾气：拿到一句，改哪一格
def 夸(s):   s["久"] = min(s["久"] + 1, 3); return "说得更久"
def 怕(s):   s["动"] = min(s["动"] + 1, 4); return "说得更吓人"
def 好心(s): s["动"] = max(s["动"] - 1, 0); return "往好里说"
def 耳背(s):
    s["在"] = 东西邻[s["在"]]; s["物"] = 东西[s["在"]]; return "听岔了地方"
def 省字(s): s["久"] = 0; return "嫌啰嗦，砍了半截"
def 原样(s): return "原样"

村 = {  # 名字: (脾气, 邻居们)
    "王婆":   (夸,   ["李瞎子", "赵屠"]),
    "李瞎子": (耳背, ["王婆", "孙先生", "小六"]),
    "赵屠":   (怕,   ["王婆", "钱寡妇"]),
    "孙先生": (省字, ["李瞎子", "钱寡妇"]),
    "钱寡妇": (好心, ["赵屠", "孙先生", "小六"]),
    "小六":   (原样, ["李瞎子", "钱寡妇", "你"]),
}

def 念(s):
    return f"你在{s['在']}{动作梯[s['动']]}{s['物']}，{程度梯[s['久']]}"

def 坏(s):  # 这句话对你有多坏
    return s["动"] + (1 if s["在"] in ("坟", "庙") else 0)

def 传(起头, s, seed):
    rnd = random.Random(seed)
    听过 = {}
    队 = [(起头, dict(s), "你")]
    while 队:
        人, 句, 从谁 = 队.pop(0)
        if 人 in 听过: continue
        if 人 == "你":
            听过["你"] = (句, 从谁, "")
            continue
        脾气, 邻 = 村[人]
        句 = dict(句); 改 = 脾气(句)
        听过[人] = (句, 从谁, 改)
        rnd.shuffle(邻)
        for n in 邻[:2]:
            队.append((n, 句, 人))
    return 听过

if __name__ == "__main__":
    起头 = sys.argv[1] if len(sys.argv) > 1 else "王婆"
    s = {"在": sys.argv[2] if len(sys.argv) > 2 else "柿子树", "动": 0, "久": 0}
    s["物"] = 东西[s["在"]]
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    print("你对", 起头, "说：", 念(s))
    听过 = 传(起头, s, seed)
    for 人, (句, 从, 改) in 听过.items():
        if 人 == "你": continue
        对你 = ["冲你笑", "照常", "躲着你", "关上门", "去叫保长"][min(坏(句), 4)]
        print(f"  {人}（从{从}那听来，{改}）：{念(句)}  → 明天见你{对你}")
    if "你" in 听过:
        句, 从, _ = 听过["你"]
        print("回到你耳朵里（", 从, "说的）：", 念(句))
    else:
        print("这句话没回到你耳朵里。")
